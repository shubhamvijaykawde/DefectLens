"""Build ``reports/error_gallery.md`` and its figures from the frozen thresholds."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import torch

from defectlens.config import load_config
from defectlens.eval.gallery import (
    area_summary,
    best_by_calibration_auroc,
    case_table,
    class_breakdown,
    entry_lookup,
    image_errors,
    plot_neu_cases,
    plot_visa_cases,
    rank_visa_cases,
    worst_images,
)
from defectlens.eval.scoring import detect_neu, score_visa
from defectlens.eval.thresholds import EVALUATION_SPLITS, file_sha256, read_frozen

VISA_MODELS = ("patchcore", "anomaly_dino", "efficientad")
DETECTORS = ("faster_rcnn", "faster_rcnn_aug", "dfine_s")
NOTES_TODO = (
    "TODO: written after looking at the figures; kept in `reports/error_gallery_notes.md` so "
    "regenerating this file does not overwrite them."
)


def build_gallery(
    frozen_path: Path, ratio: float, top_k: int, out_md: Path, fig_dir: Path, notes: Path,
    device: str,
) -> str:
    entries, meta = read_frozen(frozen_path)
    sha = file_sha256(frozen_path)
    table = entry_lookup(entries, ratio)
    if not table:
        msg = f"no frozen thresholds for fn_fp_ratio={ratio:g}"
        raise ValueError(msg)
    cfg = load_config(["data=visa"])
    categories = list(cfg.data.categories)
    lines = [
        "# Error gallery (Phase 4a)", "",
        "Generated by `scripts/error_gallery.py`. It reads the evaluation splits "
        "(`threshold_evaluation`, `test`) at the frozen thresholds of "
        f"`reports/frozen_thresholds.json` (SHA-256 `{sha}`), for fn_fp_ratio = {ratio:g}. "
        "It changes no threshold, and nothing here feeds back into one: a later change would need "
        "a new untouched subset or a disclosed result.", "",
        "Figures show the lowest-scoring anomalous images and the highest-scoring normal images "
        "(VisA) and the worst images by `ratio * FN + FP` (NEU-DET). For VisA one model per "
        "category is drawn, the one with the best image AUROC on `threshold_calibration` (a "
        "calibration-side choice); the tables cover every model.", "",
    ]

    lines += ["## VisA: summary at the frozen thresholds", "",
              "| category | model | threshold | missed / anomalous | false alarms / normal | "
              "median defect area, missed | median defect area, caught |",
              "|---|---|---|---|---|---|---|"]
    detail: list[str] = []
    for category in categories:
        chosen = best_by_calibration_auroc(list(VISA_MODELS), category, Path("outputs/anomaly"))
        for model in VISA_MODELS:
            e = table[(model, category)]
            pred = score_visa(model, category, EVALUATION_SPLITS["visa"], "evaluation", device)
            areas = pred.masks.reshape(len(pred.masks), -1).mean(axis=1)
            s = area_summary(pred.scores, pred.labels, areas, e.threshold)
            lines.append(
                f"| {category} | {model}{' (drawn)' if model == chosen else ''} | "
                f"{e.threshold:.4g} | {s['n_missed']} / {s['n_anomalous']} | "
                f"{s['n_false_alarms']} / {s['n_normal']} | "
                f"{_pct(s['median_area_missed'])} | {_pct(s['median_area_caught'])} |"
            )
            if model != chosen:
                continue
            cases = rank_visa_cases(pred.paths, pred.scores, pred.labels, areas, e.threshold, top_k)
            fig = fig_dir / f"error_gallery_visa_{category}.png"
            plot_visa_cases(pred.images, pred.maps, pred.masks, cases, e.threshold,
                            f"{category}, {model}, fn_fp_ratio {ratio:g} (threshold_evaluation)",
                            fig)
            rel = fig.relative_to(out_md.parent)
            detail += [f"### {category} ({model})", "", f"![{category}]({rel})",
                       "", f"Lowest-scoring anomalous images (top {top_k}):", "",
                       *case_table(cases["anomalous"]), "",
                       f"Highest-scoring normal images (top {top_k}):", "",
                       *case_table(cases["normal"]), ""]
    lines += [""] + ["## VisA: the drawn model per category", ""] + detail

    lines += ["## NEU-DET: errors at the frozen thresholds", ""]
    best_val, best_name = -1.0, DETECTORS[0]
    per_detector = {}
    for run in DETECTORS:
        dets, gts, names, _, ckpt = detect_neu(run, EVALUATION_SPLITS["neu_det"], "evaluation",
                                              torch.device(device))
        e = table[(run, "all")]
        errors = [image_errors(d, g, e.threshold) for d, g in zip(dets, gts, strict=True)]
        per_detector[run] = (names, gts, errors, e)
        if ckpt["val"]["map50_95"] > best_val:
            best_val, best_name = float(ckpt["val"]["map50_95"]), run
    class_names = {i + 1: n for i, n in enumerate(_class_names())}
    for run, (names, gts, errors, e) in per_detector.items():
        lines += [f"### {run} (threshold {e.threshold:.4g})", "",
                  "| class | ground-truth boxes | missed | of which overlapped by a same-class "
                  "kept box (IoU >= 0.1) | false alarms (kept, this class) |",
                  "|---|---|---|---|---|"]
        lines += [f"| {r['class']} | {r['n_gt']} | {r['missed']} | {r['missed_overlapped']} | "
                  f"{r['false_alarms']} |"
                  for r in class_breakdown(errors, gts, class_names)]
        lines += ["", f"Worst {top_k} images by `{ratio:g} * FN + FP`:", "",
                  "| # | image | FN | FP | TP | cost |", "|---|---|---|---|---|---|"]
        lines += [f"| {n} | `{w['name']}` | {w['fn']} | {w['fp']} | {w['tp']} | {w['cost']:g} |"
                  for n, w in enumerate(worst_images(errors, names, ratio, top_k), 1)]
        lines.append("")
    names, gts, errors, e = per_detector[best_name]
    worst = worst_images(errors, names, ratio, 12)
    fig = fig_dir / "error_gallery_neu_det.png"
    images_dir = Path(load_config().data.raw_dir) / "IMAGES"
    plot_neu_cases(images_dir, names, errors, gts, worst, class_names,
                   f"{best_name} (best val AP@50:95), fn_fp_ratio {ratio:g}, test: 12 worst images",
                   fig)
    lines += [f"The figure draws {best_name}, the detector with the best val AP@50:95 "
              f"({best_val:.4f}).", "", f"![neu-det]({fig.relative_to(out_md.parent)})", ""]

    lines += ["## Notes on failure patterns", "",
              notes.read_text().rstrip() if notes.is_file() else NOTES_TODO, ""]
    text = "\n".join(lines)
    out_md.write_text(text)
    return text


def _pct(x: float) -> str:
    return "-" if np.isnan(x) else f"{100 * x:.2f}%"


def _class_names() -> list[str]:
    from defectlens.data.coco import read_coco

    cfg = load_config()
    _, names = read_coco(Path(cfg.data.processed_dir) / "val.json")
    return [names[i] for i in sorted(names)]

"""Build reports/detection_comparison.md and confusion figures from MLflow runs.

Usage: uv run python scripts/compare_detectors.py [runs=classical,faster_rcnn,dfine_s]
Run names are MLflow run names in the `defectlens` experiment (latest finished run of each).
Nothing is typed by hand: every number is read from the logged runs.
"""

from __future__ import annotations

import sys
from pathlib import Path

import mlflow

from defectlens.eval import compare
from defectlens.tracking import DEFAULT_TRACKING_URI

REPORT = Path("reports/detection_comparison.md")
FIGURES = Path("reports/figures")

NOTE = """\
**Not a fully like-for-like comparison.** `faster_rcnn_aug` matches D-FINE-S on augmentation
(both use scale/shift), but the rest of each recipe still differs, so differences below mix
architecture and recipe effects and cannot be attributed to either one:

- D-FINE-S: 640 px input, effective batch 16, AdamW, 40 epochs, early stopping configured
  (patience 10).
- Faster R-CNN: 480 px, batch 4, SGD, 30 epochs, no early stopping. `faster_rcnn` (without
  scale/shift) is the original recipe; `faster_rcnn_aug` adds only `scale_translate: 0.5`.
- Both keep the best-val checkpoint (by val AP@50:95), so checkpoint selection is the same.
- D-FINE's best epoch was its last (40), so it may not have converged; Faster R-CNN's best epoch is
  earlier than its last. Early stopping never fired for D-FINE (see the protocol table).
- One seed per detector and 270 images per split: small differences are not shown to be meaningful.
- recall, precision and FP/image are at a fixed score threshold of 0.5. D-FINE's sigmoid scores and
  Faster R-CNN's softmax scores are calibrated differently, so a fixed 0.5 favours one or the other;
  `recall_max` (any score) and the AP columns do not depend on it.
- The classical baseline is class-agnostic (AP and recall treat all defects as one class)."""


def main() -> int:
    args = dict(a.split("=", 1) for a in sys.argv[1:] if "=" in a)
    names = args.get("runs", "classical,faster_rcnn,dfine_s").split(",")
    mlflow.set_tracking_uri(DEFAULT_TRACKING_URI)
    exp = mlflow.get_experiment_by_name("defectlens")
    if exp is None:
        print("no `defectlens` experiment found")
        return 1
    client = mlflow.MlflowClient()
    runs = [compare.load_run(client, exp.experiment_id, n) for n in names]

    classes: list[str] = []
    parts = ["# Detector comparison", "",
             "Generated by `scripts/compare_detectors.py` from MLflow runs "
             + ", ".join(f"`{r.name}`={r.run_id[:8]}" for r in runs)
             + ". Val is read at each run's best epoch; test was scored once per run.", "",
             NOTE, ""]
    cms = []
    for r in runs:
        if r.confusion_md:
            classes, cm = compare.parse_confusion_md(r.confusion_md)
            cms.append((r, cm))
    parts += ["## Headline metrics", "", compare.headline_table(runs), "",
              "## Training protocol (from each run's logged config)", "",
              compare.protocol_table(runs), "",
              "## Per class (test)", "", compare.per_class_table(runs, classes), ""]
    parts += ["## Confusion matrices (test, IoU 0.5, score >= 0.5)", ""]
    for r, cm in cms:
        fig = FIGURES / f"confusion_{r.name}.png"
        compare.plot_confusion(cm, classes, f"{r.name}: test confusion matrix", fig)
        s = compare.confusion_summary(cm, classes)
        parts += [f"### {r.name}", "", f"![{r.name}](figures/{fig.name})", "",
                  f"Correct class {s['correct']}, wrong class {s['wrong_class']}, missed "
                  f"{s['missed']}, false alarms on background {s['false_alarms']}.", ""]
    REPORT.write_text("\n".join(parts))
    print(REPORT.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())

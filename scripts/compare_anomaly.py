"""Build reports/anomaly_comparison.md and reports/figures/few_shot_curve.png from MLflow runs.

Usage: uv run python scripts/compare_anomaly.py [shots=1,5,10] [categories=cashew,candle,...]
Full-data runs: latest finished `<model>_<category>` of Phase 3a/3b. Few-shot runs: `phase=3c`.
Nothing is typed by hand: every number is read from the logged runs. All runs are scored on
`threshold_calibration`; `threshold_evaluation` is not read.
"""

from __future__ import annotations

import sys
from pathlib import Path

import mlflow

from defectlens.eval import anomaly_compare as ac
from defectlens.tracking import DEFAULT_TRACKING_URI

REPORT = Path("reports/anomaly_comparison.md")
NOTES = Path("reports/anomaly_comparison_notes.md")  # hand-written, appended on every run
FIGURE = Path("reports/figures/few_shot_curve.png")

NOTE = """\
- Every run here is scored on `threshold_calibration` (75 images for cashew, 100 for the others);
  `threshold_evaluation` is not read by this script (Phase 4a's one frozen-threshold evaluation
  is in `reports/thresholds.md`). AUROC and AUPRO are threshold-free.
- Full-data rows are one run per model and category (seed 42, untuned defaults). With 75-100
  images and a single seed, small gaps are not shown to be meaningful.
- "fit" is each model's own training step: PatchCore embeds the images and builds a 1% coreset,
  AnomalyDINO embeds the patches (no coreset), EfficientAD trains 70,000 steps. It is not
  comparable as an inference cost; latency is measured in Phase 5. `peak VRAM` is allocated GPU
  memory per run. Peak RAM is left out: for the Phase 3a runs it was a process-wide maximum.
- EfficientAD holds out 10% of the training normals to compute its map normalisation, so it
  trains on 90% of the images; the other two use all of them.
- Few-shot: the k images come from saved draws (`data/splits/few_shot_draws.json`); within a
  draw the 1-shot set is part of the 5-shot set, which is part of the 10-shot set. Draws are
  independent between categories. `±` is the sample standard deviation over the draws (n shown),
  not a confidence interval. The `mean` row averages the categories within each draw first.
- Dashed lines in the figure and the "full data" column are the full-data runs of the same
  category (for the mean panel, the mean over categories). Each panel of the figure
  has its own y-axis because the categories differ a lot."""


def main() -> int:
    args = dict(a.split("=", 1) for a in sys.argv[1:] if "=" in a)
    shots = [int(k) for k in args.get("shots", "1,5,10").split(",")]
    categories = args.get("categories", "cashew,candle,pcb1,macaroni2").split(",")
    mlflow.set_tracking_uri(DEFAULT_TRACKING_URI)
    exp = mlflow.get_experiment_by_name("defectlens")
    if exp is None:
        print("no `defectlens` experiment found")
        return 1
    runs = ac.load_runs(mlflow.MlflowClient(), exp.experiment_id)
    full = ac.full_runs(runs)
    models = [m for m in ac.MODELS if any((m, c) in full for c in categories)]

    parts = ["# Anomaly detection comparison (VisA, threshold_calibration)", "",
             "Generated by `scripts/compare_anomaly.py` from MLflow runs; "
             "nothing is typed by hand.", "",
             NOTE, "", "## Three models, full training data", ""]
    for metric in ac.METRICS:
        table = ac.full_table(full, models, categories, metric)
        parts += [f"### {ac.METRIC_LABELS[metric]}", "", table, ""]
    parts += ["### Training cost", "", ac.cost_table(full, models, categories), "",
              "Run ids: " + ", ".join(f"`{m}_{c}`={full[m, c].run_id[:8]}"
                                      for m in models for c in categories if (m, c) in full), ""]

    refs: dict[str, dict[str, float]] = {}
    dino_few = [r for r in runs if r.phase == "3c" and r.model == "anomaly_dino"]
    if dino_few:
        parts += ["## Few-shot AnomalyDINO", "",
                  f"{len(dino_few)} runs (latest per name). Figure: `{FIGURE.as_posix()}` "
                  "(image AUROC).", ""]
        for m in ac.MODELS:
            per = {c: full[m, c].metrics["image_auroc"] for c in categories if (m, c) in full}
            if len(per) == len(categories):
                refs[m] = {**per, "mean": sum(per.values()) / len(per)}
        for metric in ac.METRICS:
            values = ac.few_shot_values(runs, "anomaly_dino", metric)
            stats = ac.few_shot_stats(values, categories, shots)
            dino_ref: dict[str, float] = {}
            per = {c: full["anomaly_dino", c].metrics[metric] for c in categories
                   if ("anomaly_dino", c) in full}
            if len(per) == len(categories):
                dino_ref = {**per, "mean": sum(per.values()) / len(per)}
            parts += [f"### {ac.METRIC_LABELS[metric]}", "",
                      ac.few_shot_table(stats, dino_ref, shots, [*categories, "mean"]), ""]
            if metric == "image_auroc":
                ac.plot_few_shot(values, stats, refs, categories, shots, FIGURE, metric)
        draws = sorted({r.run_id[:8] for r in dino_few})
        parts += [f"Few-shot run ids: {', '.join(f'`{d}`' for d in draws)}", ""]
    else:
        parts += ["## Few-shot AnomalyDINO", "", "TODO: no phase-3c runs in MLflow yet.", ""]

    parts += ["## Notes", "",
              NOTES.read_text().rstrip() if NOTES.is_file()
              else "TODO: hand-written notes go in `reports/anomaly_comparison_notes.md`.", ""]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(parts))
    print(f"wrote {REPORT}" + (f" and {FIGURE}" if dino_few else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
